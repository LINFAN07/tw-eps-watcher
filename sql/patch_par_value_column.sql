-- 每季的面額欄位（2026-07-22）
--
-- 為什麼需要：每股淨值與股數都是用面額換算的
--     BVPS = 面額 × 權益 / 股本      股數 = 股本 / 面額
-- 但面額目前是「執行下載時抓一次就丟」的暫態資料，資料庫沒有任何欄位
-- 記錄「這一季用的面額是多少、哪天抓的」。這牴觸專案最高原則：
-- 對任何一個寫入的數字，都要能回答「這是誰給的？哪一天的」。
--
-- 具體失效情境（不是假想，台灣 2014 年起面額自由化）：
-- 某公司 2021 年由面額 10 元改為 1 元。2021 年以前各季的 CapitalStock
-- 是以 10 元面額申報的，當時的 BVPS = 10 × 權益 / 股本 本來就是對的。
-- 而 patch_par_value.py 用【今天的面額】一律乘 par/10 = 0.1
-- → 2021 年以前每一季的淨值被改成正確值的 1/10、股數被改成 10 倍。
-- P/B 河流圖的十年估值帶整段扭曲，而 pb_reliable 的門檻是用回測
-- （吃同一張表）算出來的。
--
-- 更糟的是事後無從查證：沒有這個欄位，就分不出哪些季是對的。
-- audit_external 也抓不到——它只驗最新一期，且 check_bvps 用 8% 佔比門檻，
-- 單一公司整條歷史全錯永遠不會亮紅燈。
--
-- 存了這欄之後：
--   1. 每一季的淨值都能追溯到當期使用的面額
--   2. 稽核可以區分「淨值算錯」與「面額用錯」
--   3. 面額變更的公司可以只重算變更之後的季度

ALTER TABLE balance_sheet_quarterly
  ADD COLUMN IF NOT EXISTS par_value NUMERIC;

COMMENT ON COLUMN balance_sheet_quarterly.par_value IS
  '該季計算每股淨值與股數時所用的普通股面額（元）。來源：交易所公司基本資料 '
  't187ap03_L／mopsfin_t187ap03_O／mopsfin_t187ap03_R。'
  'NULL 代表該季寫入時取不到面額——那些列的 book_value_per_share 與 '
  'shares_thousand 不可信任，不得用於估值。';
