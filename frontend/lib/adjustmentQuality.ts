// 除權息還原的官方背書程度（估值卡片與排行榜共用的單一真相來源）
//
// 權威來源是 valuations.unofficial_adjustments（見 schema.sql）：
// 該股歷史序列中，有幾次除權息是沒有交易所官方因子背書、只能自算的。
// 由 calculate_valuation.py 寫入，值出自 price_adjust.unofficial_adjustments()，
// 與實際做還原的 back_adjust() 共用同一份因子建構邏輯，兩邊不會漂移。
//
// 【這個旗標刻意不進 isPeUnreliable()】
// 它的語意是「這段還原有沒有官方背書」，不是「這支股票的估值有問題」。
// 自算公式對配息與配股完全正確，涵蓋不了的只有現金增資與減資，
// 而那兩者不會出現在 dividends 表裡，我們無從得知它是否發生過。
// 併進 isPeUnreliable 會把 859 檔上櫃股幾乎整批踢出排行榜——
// 那是把「不知道」當成「有問題」，違反資料誠信原則第 3 條。
// 所以它只在畫面上告知，不改變排名與推薦。
//
// 為什麼上櫃股特別容易命中（2026-08-03 實測）：
//   TWSE 的 TWT49U 可查 10 年區間 → 上市官方因子涵蓋 1,031/1,093 家、回溯 2016 年
//   TPEx 的端點只給當日、漏跑永久補不回 → 上櫃僅 83/887 家且只有 2025 年起
// 影響方向是固定的：未還原的資本事件讓歷史股價偏高 → 歷史倍數偏高 →
// 目標價虛高 →【看起來比實際便宜】，所以受影響的股票會往便宜榜頂端跑。
//
// 【排行榜刻意不顯示這個提示，只有個股頁顯示】（2026-08-05 決定）
// 上一段那個「會往榜首跑」的推論成立，但據此在榜上標記沒有作用——量測四個
// 便宜榜當下的命中率：前 50 名有 42~48% 掛標籤（P/E 24 檔、P/B 21、P/S 21、
// P/FCF 24），全候選也是 45%。一半的列都有的標籤，區分度是零。
// 更關鍵的是掛標籤者的市場別幾乎清一色上櫃與興櫃（P/FCF 前 50 的 24 檔全是
// 上櫃），因為「上櫃 → TPEx 官方因子拿不到 → 只能自算」近乎恆等式——
// 標籤實際上是在重複顯示「這支是上櫃股」，而市場別在表格裡本來就有欄位。
// 調高門檻救不了：掛標籤者的次數中位數是 7，拉到 10 只是換一批人掛。
// 排行榜是掃視場景，這種註記只會被讀成「這支有問題」（97% 偏差 <5%），
// 或反過來被讀成「沒標籤 = 安全」——後者更危險，因為真正該擋的
// unadjusted_capital_events 涵蓋範圍與本標籤不同，且已在後端排除。
// 個股頁保留：使用者已經決定看這一支，透明度說明成本低且答得出「為什麼」。

// 幾次以上才提示。1～2 次的曝險對整條歷史倍數分布的影響通常在雜訊範圍內，
// 全部都標會讓提示變成背景雜音（近 10 年配過股的公司佔三成以上）。
const NOTICE_THRESHOLD = 3

/** 未達門檻回 null，呼叫端據此決定顯不顯示——不另外提供布林函式，
 *  免得兩個入口對「要不要提示」各判一次而漂移 */
export function adjustmentNotice(v: {
  unofficial_adjustments?: number | null
}): string | null {
  const n = v.unofficial_adjustments ?? 0
  if (n < NOTICE_THRESHOLD) return null
  return `歷史股價的除權息還原有 ${n} 次未取得交易所公告因子，改用股利自行推算。` +
    `配息與配股的還原不受影響，但這段期間若發生過減資或現金增資，` +
    `目標價會偏高（看起來比實際便宜）。`
}
